#!/usr/bin/env bash
# NEXUS 066. Run manually from the Codespace terminal.
# Creates only synthetic data. Never enables WhatsApp, publishing or cloud production services.
set -euo pipefail
if [[ "${CODESPACES:-}" != "true" ]]; then
  echo "Segurança: comando permitido somente dentro de GitHub Codespaces." >&2; exit 1
fi
if [[ ! "${CODESPACE_NAME:-}" =~ ^[a-z0-9-]+$ ]]; then
  echo "Ambiente Codespaces inválido: nome ausente." >&2; exit 1
fi
if [[ ! "${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-}" =~ ^[a-z0-9.-]+$ ]]; then
  echo "Ambiente Codespaces inválido: domínio ausente." >&2; exit 1
fi
cd "$(dirname "$0")/../.."
envfile=.env.nexus-demo
origin="https://${CODESPACE_NAME}-39164.${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN}"
if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1 || ! docker info >/dev/null 2>&1; then
  echo "Docker-in-Docker não iniciou neste Codespace. Não foi realizado deploy." >&2; exit 1
fi
if [[ ! -f "$envfile" ]]; then
  if docker volume ls --format '{{.Name}}' | grep -Fxq 'nexus064-demo_demo_mysql_data'; then
    echo "Volume existente sem arquivo de credenciais. Não gerar senha nova para banco anterior." >&2; exit 1
  fi
  umask 077
  cat > "$envfile" <<ENVFILE
# Senhas exclusivamente do demonstrador Codespaces. Nunca enviar ou publicar.
MYSQL_PASSWORD=$(openssl rand -hex 24)
MYSQL_ROOT_PASSWORD=$(openssl rand -hex 24)
AUTH_SECRET=$(openssl rand -hex 32)
NEXUS_DEMO_PASSWORD=$(openssl rand -hex 24)
ENVFILE
fi
chmod 600 "$envfile"
set -a
# Generated by this script; never source arbitrary files from another project.
source "$envfile"
set +a
export NEXUS_DEMO_ORIGIN="$origin"
args=(compose --env-file "$envfile" -f scripts/nexus/compose.demo-064.yml)
# NEXUS 071: optional Codespaces secret. Docker Compose mounts this as a read-only
# /run/secrets file rather than placing the access token in app environment or .env.
# No secret => old demo config, no dispatch and no change to saved drafts.
if [[ -n "${NEXUS_REA_DISPATCH_TOKEN:-}" ]]; then
  args+=(-f scripts/nexus/compose.rea-071.secrets.yml)
  echo "NEXUS REA: autorizacao Codespaces detectada; usando montagem segura de segredo."
else
  echo "NEXUS REA: envio desabilitado ate autorizacao Codespaces."
fi
docker "${args[@]}" config --quiet
docker "${args[@]}" up -d --build
echo ""
echo "NEXUS — demonstrador iniciado. A porta encaminhada DEVE permanecer PRIVADA no GitHub."
echo "Abra a guia PORTAS/PORTS do Codespaces, procure 39164 e confirme 'Private'."
echo "URL após a porta estar encaminhada: $origin/auth/login"
echo "E-mail: demo@nexus.invalid"
echo "Sua senha de teste está no arquivo oculto .env.nexus-demo, campo NEXUS_DEMO_PASSWORD."
echo "Não compartilhe senhas, tokens ou screenshots do arquivo."
echo "Para desligar o aplicativo preservando os dados:"
echo "docker compose --env-file .env.nexus-demo -f scripts/nexus/compose.demo-064.yml down"
echo "Pare também o Codespace quando terminar para não consumir horas da sua cota."
